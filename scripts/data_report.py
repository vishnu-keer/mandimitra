"""Write docs/DATA_REPORT.md from the files actually on disk.

    python scripts/data_report.py

Every number in the report is computed here from data/raw, data/interim,
data/processed and outputs/. Nothing is typed in by hand, so the report cannot
drift from the data. Re-run it after any pipeline change.
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd

from src import config
from src.data_prep import load_clean
from src.features import load_features
from src.splits import usable_mask


def main():
    raw = pd.read_csv(config.RAW_SUBSET_PATH)
    raw["commodity"] = raw["Commodity_Name"].str.strip().str.title()
    raw["market"] = raw["Centre_Name"].str.strip().str.title()
    clean, feats = load_clean(), load_features()
    excl_path = config.OUTPUTS / "excluded.csv"
    excluded = pd.read_csv(excl_path) if excl_path.exists() else pd.DataFrame()
    bounds_path = config.OUTPUTS / "split_boundaries.csv"
    bounds = pd.read_csv(bounds_path) if bounds_path.exists() else pd.DataFrame()

    rows = []
    for (c, m), r in raw.groupby(["commodity", "market"]):
        cl = clean[(clean["commodity"] == c) & (clean["market"] == m)]
        f = feats[(feats["commodity"] == c) & (feats["market"] == m)]
        span = (cl["date"].max() - cl["date"].min()).days + 1 if not cl.empty else 0
        obs = int(cl["observed"].sum()) if not cl.empty else 0
        usable = {h: int(usable_mask(f, h).sum()) if not f.empty else 0
                  for h in config.HORIZONS}
        passes = max(usable.values()) >= config.MIN_ROWS_PER_PAIR
        rows.append({
            "Commodity": c, "Market": m,
            "Raw rows": len(r),
            "Zero price (source NA code)": int((r["Price"] == 0).sum()),
            "First date": cl["date"].min().date() if not cl.empty else "-",
            "Last date": cl["date"].max().date() if not cl.empty else "-",
            "Calendar days": span,
            "Days with a real price": obs,
            "Reporting %": round(100 * obs / span, 1) if span else 0.0,
            "Feature rows": len(f),
            "Carried forward %": round(100 * (~f["observed"]).mean(), 1) if len(f) else 0.0,
            **{f"Usable h={h}": usable[h] for h in config.HORIZONS},
            "Gate": "PASS" if passes else "excluded",
        })
    cov = pd.DataFrame(rows)
    cov["_order"] = (cov["Gate"] != "PASS").astype(int)          # PASS first
    cov = cov.sort_values(["_order", "Market", "Commodity"]).drop(columns="_order")

    out = [
        "# Dataset and pipeline report",
        "",
        f"_Generated by `scripts/data_report.py` on {date.today().isoformat()} "
        "from the files on disk. Do not edit by hand; re-run the script._",
        "",
        "## Source",
        "",
        "Official data.gov.in daily wholesale price files for Onion and Tomato "
        "(Department of Consumer Affairs, Price Monitoring Cell), 01-01-2009 to "
        "28-04-2015. Untouched copies and their SHA-256 hashes: "
        "`data/raw/source/SOURCE.md`. Unit: **Rs. per quintal, wholesale**, as "
        "stated by the publisher.",
        "",
        "## Coverage per commodity-market pair",
        "",
        cov.to_markdown(index=False),
        "",
        "**Definitions.**",
        "- *Zero price*: the source records `0` where no price was reported. "
        "These are treated as missing, never as a price of zero.",
        "- *Days with a real price*: calendar days on which the mandi reported a "
        "non-zero price.",
        f"- *Carried forward %*: share of feature rows whose `price_t` was carried "
        f"forward from an earlier reported day (at most {config.MAX_FFILL_DAYS} "
        "days). These rows are inputs only.",
        "- *Usable h=k*: rows with a complete feature vector **and** a genuinely "
        "reported target price k days later. Only these are ever trained on or "
        "scored. Carried-forward targets are never scored.",
        f"- *Gate*: a pair is evaluated only if it has at least "
        f"{config.MIN_ROWS_PER_PAIR} usable rows. The gate was set before any of "
        "these markets were examined and was not changed afterwards.",
        "",
    ]
    if not excluded.empty:
        out += ["## Exclusions, with reasons", "",
                excluded.to_markdown(index=False), ""]
    if not bounds.empty:
        show = bounds[["commodity", "market", "horizon", "train_start",
                       "train_end", "cv_start", "cv_end", "cv_folds",
                       "test_start", "test_end", "n_train", "n_cv_scored",
                       "n_test_scored"]]
        out += ["## Evaluation boundaries (evaluated pairs)", "",
                "`train` is the development block the final models are fitted "
                "on; `cv` is the span scored by the rolling-origin folds inside "
                "it; `test` is scored once, after selection.", "",
                show.to_markdown(index=False), ""]
    out += ["## Known data limitations", "",
            "- Historical only: the source ends on 28 April 2015.",
            "- One price per centre per day (modal); no min/max, so the "
            "`spread_pct` feature is all-empty and is dropped automatically.",
            "- No arrivals, weather, MSP, festival or transport data.",
            "- Jodhpur and Kota report far less often than Jaipur and do not "
            "clear the gate; they are shown as excluded, not forecast.", ""]

    path = config.DOCS / "DATA_REPORT.md"
    path.write_text("\n".join(out))
    print(f"wrote {path.relative_to(config.PROJECT_ROOT)}")
    print(cov.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
